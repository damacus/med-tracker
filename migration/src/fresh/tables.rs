async fn create_table(
    manager: &SchemaManager<'_>,
    table: TableCreateStatement,
) -> Result<(), DbErr> {
    let sql = table.to_string(PostgresQueryBuilder);
    manager
        .create_table(table)
        .await
        .map_err(|error| DbErr::Migration(format!("{error}; statement: {sql}")))
}
