ALTER TABLE public.notification_events
  ADD COLUMN intended_at timestamp(6) without time zone,
  ADD COLUMN expires_at timestamp(6) without time zone;

CREATE TABLE public.notification_deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_event_id bigint NOT NULL REFERENCES public.notification_events(id),
  subscription_id bigint REFERENCES public.push_subscriptions(id) ON DELETE SET NULL,
  household_id bigint NOT NULL REFERENCES public.households(id),
  account_id bigint NOT NULL REFERENCES public.accounts(id),
  status varchar NOT NULL DEFAULT 'pending',
  attempt_count integer NOT NULL DEFAULT 0,
  next_attempt_at timestamp(6) without time zone NOT NULL,
  claimed_at timestamp(6) without time zone,
  outcome varchar(64),
  created_at timestamp(6) without time zone NOT NULL DEFAULT timezone('UTC', clock_timestamp()),
  updated_at timestamp(6) without time zone NOT NULL DEFAULT timezone('UTC', clock_timestamp()),
  CONSTRAINT notification_deliveries_event_subscription_unique UNIQUE (notification_event_id, subscription_id),
  CONSTRAINT notification_deliveries_status_check CHECK (status IN ('pending','sending','accepted','expired','permanent','uncertain','invalid')),
  CONSTRAINT notification_deliveries_attempt_check CHECK (attempt_count BETWEEN 0 AND 5),
  CONSTRAINT notification_deliveries_outcome_check CHECK (outcome IS NULL OR length(outcome) <= 64)
);

CREATE INDEX notification_deliveries_due_idx ON public.notification_deliveries (household_id, account_id, next_attempt_at) WHERE status='pending';
CREATE INDEX notification_deliveries_stale_idx ON public.notification_deliveries (household_id, account_id, claimed_at) WHERE status='sending';
