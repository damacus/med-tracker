ALTER TABLE public.medication_review_prompts
  ADD COLUMN evidence_source_fingerprint varchar(32);
UPDATE public.medication_review_prompts p
SET evidence_source_fingerprint=CASE WHEN
  p.evidence_source_name=e.source_name AND
  p.evidence_source_url=e.source_url AND
  p.evidence_source_version=COALESCE(e.source_version,'unknown') AND
  p.evidence_source_effective_on=COALESCE(e.source_effective_on,e.retrieved_on) AND
  position(p.evidence_text in e.evidence_text)>0
THEN md5(jsonb_build_array(
  e.source_name,e.source_url,e.source_version,e.source_effective_on,
  e.evidence_text,e.risk_level,e.match_confidence
)::text) ELSE 'stale' END
FROM public.medication_review_evidence_records e
WHERE e.id=p.evidence_record_id;

