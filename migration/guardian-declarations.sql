CREATE FUNCTION med_tracker.guardian_declaration_one_way()
RETURNS trigger LANGUAGE plpgsql
SET search_path=pg_catalog
AS $body$
BEGIN
  IF TG_OP='INSERT' THEN
    NEW.declared_at:=pg_catalog.clock_timestamp();
    RETURN NEW;
  END IF;
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Guardian declaration provenance is retained';
  END IF;
  IF (pg_catalog.to_jsonb(NEW)-ARRAY['withdrawn_at','revision'])
       IS DISTINCT FROM
     (pg_catalog.to_jsonb(OLD)-ARRAY['withdrawn_at','revision']) THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Guardian declaration identity is immutable';
  END IF;
  IF OLD.withdrawn_at IS NOT NULL THEN
    IF NEW IS DISTINCT FROM OLD THEN
      RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Guardian declaration withdrawal is final';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.withdrawn_at IS NULL OR NEW.revision<>OLD.revision+1 THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid guardian declaration transition';
  END IF;
  NEW.withdrawn_at:=pg_catalog.clock_timestamp();
  IF NEW.withdrawn_at<OLD.declared_at THEN
    RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Invalid guardian declaration clock order';
  END IF;
  RETURN NEW;
END;
$body$;
ALTER FUNCTION med_tracker.guardian_declaration_one_way() OWNER TO med_tracker_owner;
REVOKE ALL ON FUNCTION med_tracker.guardian_declaration_one_way() FROM PUBLIC,med_tracker_app;
CREATE TRIGGER guardian_declarations_one_way
BEFORE INSERT OR UPDATE OR DELETE ON public.guardian_declarations
FOR EACH ROW EXECUTE FUNCTION med_tracker.guardian_declaration_one_way();

