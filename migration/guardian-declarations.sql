
CREATE TABLE public.guardian_declarations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_person_id bigint NOT NULL,
  guardian_person_id bigint NOT NULL,
  origin_household_id bigint NOT NULL,
  declared_by_account_id bigint NOT NULL,
  statement_version smallint NOT NULL DEFAULT 1,
  subject_name_at_declaration text NOT NULL,
  declared_at timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
  withdrawn_at timestamptz,
  revision bigint NOT NULL DEFAULT 1,
  CONSTRAINT guardian_declarations_initial_subject UNIQUE(subject_person_id),
  CONSTRAINT guardian_declarations_link_identity
    UNIQUE(id,guardian_person_id,subject_person_id),
  CONSTRAINT guardian_declarations_distinct_people
    CHECK(subject_person_id<>guardian_person_id),
  CONSTRAINT guardian_declarations_statement CHECK(statement_version=1),
  CONSTRAINT guardian_declarations_name
    CHECK(pg_catalog.length(pg_catalog.btrim(subject_name_at_declaration))>0),
  CONSTRAINT guardian_declarations_revision
    CHECK((withdrawn_at IS NULL AND revision=1)
       OR (withdrawn_at IS NOT NULL AND revision=2 AND withdrawn_at>=declared_at)),
  CONSTRAINT guardian_declarations_subject
    FOREIGN KEY(subject_person_id) REFERENCES public.people(id) ON DELETE RESTRICT,
  CONSTRAINT guardian_declarations_guardian
    FOREIGN KEY(guardian_person_id) REFERENCES public.people(id) ON DELETE RESTRICT,
  CONSTRAINT guardian_declarations_origin
    FOREIGN KEY(origin_household_id) REFERENCES public.households(id) ON DELETE RESTRICT,
  CONSTRAINT guardian_declarations_actor
    FOREIGN KEY(declared_by_account_id) REFERENCES public.accounts(id) ON DELETE RESTRICT,
  CONSTRAINT guardian_declarations_subject_origin_participation
    FOREIGN KEY(subject_person_id,origin_household_id)
    REFERENCES public.household_memberships(person_id,household_id) ON DELETE RESTRICT,
  CONSTRAINT guardian_declarations_guardian_origin_participation
    FOREIGN KEY(guardian_person_id,origin_household_id)
    REFERENCES public.household_memberships(person_id,household_id) ON DELETE RESTRICT
);
