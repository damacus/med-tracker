CREATE TABLE public.invitation_mail_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id bigint NOT NULL REFERENCES public.households(id) ON DELETE CASCADE,
  invitation_id bigint REFERENCES public.household_invitations(id) ON DELETE SET NULL,
  original_invitation_id bigint NOT NULL,
  sender_account_id bigint NOT NULL,
  sender_membership_id bigint NOT NULL,
  sender_permissions_version integer NOT NULL,
  token_digest varchar NOT NULL,
  status varchar NOT NULL DEFAULT 'queued',
  category varchar,
  queued_at timestamp(6) without time zone NOT NULL DEFAULT timezone('UTC',clock_timestamp()),
  started_at timestamp(6) without time zone,
  finished_at timestamp(6) without time zone,
  CONSTRAINT invitation_mail_attempts_status_check CHECK (status IN ('queued','sent_to_provider','failed')),
  CONSTRAINT invitation_mail_attempts_category_check CHECK (category IS NULL OR category IN ('unavailable','provider_unavailable','uncertain')),
  CONSTRAINT invitation_mail_attempts_state_check CHECK (
    (status='queued' AND category IS NULL AND finished_at IS NULL)
    OR (status='sent_to_provider' AND category IS NULL AND started_at IS NOT NULL AND finished_at IS NOT NULL)
    OR (status='failed' AND category IS NOT NULL AND finished_at IS NOT NULL)
  )
);
CREATE INDEX invitation_mail_attempts_recent_idx ON public.invitation_mail_attempts(household_id,original_invitation_id,id DESC);
