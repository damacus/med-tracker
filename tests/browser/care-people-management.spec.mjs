import { test, expect } from './care-fixtures.mjs';
import { openCareSection } from './care-navigation.mjs';

test.use({ actionTimeout: 10000 });

test('people creation and editing preserve dependent care and existing medication access', async ({ page, careFixture }, testInfo) => {
  test.setTimeout(180000);
  const before = await careFixture.peopleProbe();
  await page.goto('/login');
  await page.getByLabel('Email address', { exact: true }).fill('persistence@example.test');
  await page.getByLabel('Password', { exact: true }).fill('password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Open Synthetic household', exact: true }).click();
  await openCareSection(page, 'People');
  await expect(page.getByRole('heading', { name: 'People', exact: true })).toBeVisible();
  const peopleUrl = page.url();
  await expect(page.getByRole('link', { name: 'Synthetic minor', exact: true })).toHaveCount(1);
  await page.getByRole('link', { name: 'Synthetic minor', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Synthetic minor', level: 1, exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Edit Person', exact: true })).toHaveCount(0);
  expect((await page.request.get(`${peopleUrl}/73002`, { maxRedirects: 0 })).status()).toBe(200);
  expect((await page.request.get(`${peopleUrl}/73002/edit`, { maxRedirects: 0 })).status()).toBe(403);
  expect(await careFixture.peopleProbe()).toEqual(before);
  await page.goto(peopleUrl);
  await page.getByRole('link', { name: 'Add Person', exact: true }).click();
  const declaration = page.getByRole('checkbox', { name: 'I declare that I am this person’s guardian.', exact: true });
  await expect(declaration).not.toBeChecked();
  await expect(declaration).toHaveAttribute('required', '');
  await expect(declaration).toHaveAccessibleDescription(/does not independently verify legal guardianship/);
  await page.getByLabel('Name', { exact: true }).fill('Synthetic browser minor');
  await page.getByLabel('Email', { exact: true }).fill('synthetic-browser-minor@example.test');
  await page.getByLabel('Date of Birth', { exact: true }).fill('2015-02-03');
  await page.getByLabel('Person Type', { exact: true }).selectOption('minor');
  await page.getByLabel('Has capacity to manage own medication', { exact: true }).uncheck();
  const formUrl = page.url();
  let createRequests = 0;
  const countCreate = request => {
    if (request.method() === 'POST' && request.url().split('?')[0] === formUrl.replace(/\/new$/, '')) createRequests += 1;
  };
  page.on('request', countCreate);
  try {
    await page.getByRole('button', { name: 'Create Person', exact: true }).click();
    expect(await declaration.evaluate(input => input.validity.valueMissing)).toBe(true);
    expect(page.url()).toBe(formUrl);
    expect(createRequests).toBe(0);
    expect(await careFixture.peopleProbe()).toEqual(before);
  } finally {
    page.off('request', countCreate);
  }
  await page.screenshot({ path: testInfo.outputPath(`loco-guardian-unchecked-${testInfo.project.name}.png`), fullPage: true });
  await declaration.check();
  await page.getByLabel('Name', { exact: true }).fill(' ');
  const invalid = page.waitForResponse(response => response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create Person', exact: true }).click();
  expect((await invalid).status()).toBe(422);
  await expect(declaration).toBeChecked();
  await expect(page.locator('[name="authenticity_token"]')).not.toHaveValue('');
  expect(await careFixture.peopleProbe()).toEqual(before);
  await expect(page.getByLabel('Email', { exact: true })).toHaveValue('synthetic-browser-minor@example.test');
  await expect(page.getByLabel('Date of Birth', { exact: true })).toHaveValue('2015-02-03');
  const nameError = await page.locator('[role="alert"] a[href="#name"]').innerText();
  await expect(page.getByLabel('Name', { exact: true })).toHaveAccessibleDescription(nameError);
  await page.getByLabel('Name', { exact: true }).fill('Synthetic browser minor');
  await page.getByRole('button', { name: 'Create Person', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Synthetic browser minor', exact: true })).toBeVisible();
  const created = await careFixture.peopleProbe();
  expect(created.person_type).toBe(1);
  expect(created.has_capacity).toBe(false);
  expect(created.manage_grant).toBe(false);
  expect(created.created_count).toBe(1);
  expect(created.participation_count).toBe(1);
  expect(created.declaration_count).toBe(1);
  expect(created.recorded_count).toBe(1);
  expect(created.withdrawn_count).toBe(0);
  expect(created.declaration_revision).toBe('1');
  expect(created.linked_carer_count).toBe(1);
  expect(created.creation_provenance).toBe(true);
  expect(created.account_count).toBe(before.account_count);
  expect(created.user_count).toBe(before.user_count);
  expect(created.subject_accounts).toBe(0);
  expect(created.subject_users).toBe(0);
  expect(created.carer).toBe(true);
  expect(created.home).toBe(true);
  expect(created.permissions_version).toBe(before.permissions_version);
  await page.screenshot({ path: testInfo.outputPath(`loco-guardian-created-${testInfo.project.name}.png`), fullPage: true });
  await page.getByRole('link', { name: 'Edit Person', exact: true }).click();
  await expect(page.locator('[name="initial_guardian_declaration"]')).toHaveCount(0);
  await expect(page.getByLabel('Person Type', { exact: true })).toHaveValue('minor');
  await expect(page.getByLabel('Has capacity to manage own medication', { exact: true })).not.toBeChecked();
  await page.getByLabel('Name', { exact: true }).fill(' ');
  const invalidEdit = page.waitForResponse(response => response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Update Person', exact: true }).click();
  expect((await invalidEdit).status()).toBe(422);
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(' ');
  await page.getByLabel('Name', { exact: true }).fill('Synthetic edited minor');
  await page.getByRole('button', { name: 'Update Person', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Synthetic edited minor', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath(`loco-person-${testInfo.project.name}.png`), fullPage: true });
  await page.goto(peopleUrl);
  await expect(page.getByRole('link', { name: 'Synthetic edited minor', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Synthetic adult', exact: true }).click();
  await page.getByRole('link', { name: 'Synthetic tablets', exact: true }).click();
  await page.getByRole('button', { name: 'Record dose', exact: true }).click();
  await page.getByRole('dialog', { name: 'Record dose', exact: true }).getByRole('button', { name: 'Record dose', exact: true }).click();
  await expect(page.getByTestId('current-supply')).toHaveText('8 tablets');
  expect((await careFixture.probe()).takes).toBe(1);
  for (const foreignPath of ['/households/foreign-fixture/people/73005', `${peopleUrl}/73005`, '/households/foreign-fixture/medications/80002']) {
    expect([403, 404]).toContain((await page.request.get(foreignPath, { maxRedirects: 0 })).status());
  }
  expect((await careFixture.peopleProbe()).foreign_supply).toBe(before.foreign_supply);

  await page.goto(peopleUrl);
  await page.getByRole('link', { name: 'Add Person', exact: true }).click();
  await page.getByRole('link', { name: 'Guardian declarations', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Guardian declarations', level: 1, exact: true })).toBeVisible();
  const captured = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Synthetic browser minor', level: 2, exact: true }) });
  await expect(captured).toHaveCount(1);
  await expect(captured.getByText('Declaration recorded', { exact: true })).toBeVisible();
  await expect(captured.getByText('Name recorded when the declaration was made.', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Synthetic edited minor', exact: true })).toHaveCount(0);
  await expect(captured.locator('[name="revision"]')).toHaveValue('1');
  await expect(captured.locator('[name="authenticity_token"]')).not.toHaveValue('');
  await expect(captured.getByRole('button', { name: 'Withdraw my declaration', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath(`loco-guardian-recorded-${testInfo.project.name}.png`), fullPage: true });
  const withdraw = page.waitForResponse(response => response.request().method() === 'POST' && /\/profile\/guardian-declarations\/\d+\/withdraw$/.test(new URL(response.url()).pathname));
  await captured.getByRole('button', { name: 'Withdraw my declaration', exact: true }).click();
  expect((await withdraw).status()).toBe(303);
  await expect(captured.getByText('Withdrawn', { exact: true })).toBeVisible();
  await page.reload();
  await expect(captured.getByText('Withdrawn', { exact: true })).toBeVisible();
  await expect(captured.getByRole('button', { name: 'Withdraw my declaration', exact: true })).toHaveCount(0);
  await expect(captured.locator('form')).toHaveCount(0);
  const withdrawn = await careFixture.peopleProbe();
  expect(withdrawn.declaration_count).toBe(1);
  expect(withdrawn.recorded_count).toBe(0);
  expect(withdrawn.withdrawn_count).toBe(1);
  expect(withdrawn.declaration_revision).toBe('2');
  expect(withdrawn.captured_name).toBe('Synthetic browser minor');
  expect(withdrawn.withdrawal_provenance).toBe(true);
  expect(withdrawn.creation_provenance).toBe(true);
  expect(withdrawn.participation_count).toBe(1);
  expect(withdrawn.linked_carer_count).toBe(1);
  expect(withdrawn.carer).toBe(true);
  expect(withdrawn.home).toBe(true);
  expect(withdrawn.manage_grant).toBe(false);
  expect(withdrawn.account_count).toBe(before.account_count);
  expect(withdrawn.user_count).toBe(before.user_count);
  expect(withdrawn.subject_accounts).toBe(0);
  expect(withdrawn.subject_users).toBe(0);
  expect((await careFixture.probe()).takes).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath(`loco-guardian-withdrawn-${testInfo.project.name}.png`), fullPage: true });
});
